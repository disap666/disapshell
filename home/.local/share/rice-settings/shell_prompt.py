#!/usr/bin/python3
import json,re,shlex,sys
from pathlib import Path
from datetime import datetime
import waybar
BASE=Path.home()/'.config/rice-theme'
FILE=BASE/'prompt.json'
SOURCE=BASE/'prompt.zsh'
ZSHRC=Path.home()/'.zshrc'
STATE=Path.home()/'.local/state/rice-settings/prompt'
DEFAULT=dict(style='two-line',prefix='╭─',symbol='❯',bottomPrefix='╰─',accent='#c6acee',directory='#a8c9f5',success='#b4d3ad',error='#eaa2b1',showUser=False,showHost=False,showTime=False,showGit=False,bold=False)
FIELDS=[dict(key='style',label='Стиль приглашения',kind='choice',values=['minimal','two-line','boxed'])]+[
    dict(key=k,label=l,kind='text') for k,l in [('prefix','Первые символы · верхняя строка'),('bottomPrefix','Начало нижней строки'),('symbol','Символ перед командой')]]+[
    dict(key=k,label=l,kind='color') for k,l in [('accent','Цвет первых символов'),('directory','Цвет пути'),('success','Цвет успешной команды'),('error','Цвет ошибки')]]+[
    dict(key=k,label=l,kind='bool') for k,l in [('showUser','Показывать имя пользователя'),('showHost','Показывать имя компьютера'),('showTime','Показывать время'),('showGit','Показывать ветку Git'),('bold','Жирный текст')]]
PRESETS=[dict(name='Минимальный',settings=dict(style='minimal',symbol='❯',showUser=False,showHost=False)),dict(name='Две строки',settings=dict(style='two-line',prefix='╭─',bottomPrefix='╰─',symbol='❯')),dict(name='Классический',settings=dict(style='minimal',symbol='$',showUser=True,showHost=True)),dict(name='Рамка',settings=dict(style='boxed',prefix='┌─',bottomPrefix='└─',symbol='➜'))]
def read():
    try:return dict(DEFAULT,**json.loads(FILE.read_text()))
    except FileNotFoundError:return DEFAULT.copy()
def validate(data):
    if set(data)!=set(DEFAULT):raise ValueError('Некорректные настройки приглашения')
    for field in FIELDS:
        value=data[field['key']]
        if field['kind']=='text':
            if not isinstance(value,str) or len(value)>32 or any(ord(c)<32 or c in '`\\' for c in value):raise ValueError('Используй до 32 печатных символов без обратной кавычки и обратного слеша')
        elif field['kind']=='color':
            if not isinstance(value,str) or not re.fullmatch(r'#[0-9a-fA-F]{6}',value):raise ValueError(field['label'])
        elif field['kind']=='bool':
            if not isinstance(value,bool):raise ValueError(field['label'])
        elif value not in field['values']:raise ValueError(field['label'])
    return data
def literal(text):
    # Percent escapes are the only expansion used by this managed prompt.
    return text.replace('%','%%')
def render(data):
    accent='%F{'+data['accent']+'}';directory='%F{'+data['directory']+'}'
    leading='%B' if data['bold'] else ''
    leading+=accent+literal(data['prefix'])+'%f '
    if data['showTime']:leading+='%D{%H:%M} '
    if data['showUser']:leading+='%n'
    if data['showHost']:leading+=('@' if data['showUser'] else '')+'%m'
    if data['showUser'] or data['showHost']:leading+=' '
    leading+=directory+'%~%f'
    bottom=(accent+literal(data['bottomPrefix'])+'%f ') if data['style']!='minimal' else ''
    symbol=literal(data['symbol'])+'%f '+('%b' if data['bold'] else '')
    code='# Generated by rice-settings. User strings are quoted and prompt-escaped.\n'
    code+='function _rice_prompt_render() {\n  unsetopt promptsubst\n  local rc=$1\n  local line='+shlex.quote(leading)+'\n'
    if data['showGit']:
        code += '  local branch=$(command git symbolic-ref --quiet --short HEAD 2>/dev/null)\n'
        code += '  branch=${branch//[^[:alnum:]_.-]/?}\n'
        code += '  [[ -n $branch ]] && line+=" %F{'+data['accent']+'}git:${branch}%f"\n'
    code+='  local color='+shlex.quote(data['success'])+'\n  (( rc )) && color='+shlex.quote(data['error'])+'\n'
    if data['style']=='minimal':code+='  PROMPT="${line} %F{${color}}"'+shlex.quote(symbol)+'\n'
    else:code+='  PROMPT="${line}"$\'\\n\''+shlex.quote(bottom)+'"%F{${color}}"'+shlex.quote(symbol)+'\n'
    code+='}\n'
    return code
LOADER='''
# rice-settings:prompt-loader
autoload -Uz add-zsh-hook
typeset -g _rice_prompt_original=$PROMPT
typeset -g _rice_prompt_subst_original=$options[promptsubst]
function _rice_prompt_refresh() {
    local rc=$?
    if [[ -r "$HOME/.config/rice-theme/prompt.zsh" ]]; then
        source "$HOME/.config/rice-theme/prompt.zsh"
        _rice_prompt_render "$rc"
    elif (( $+functions[_rice_prompt_render] )); then
        unfunction _rice_prompt_render
        PROMPT=$_rice_prompt_original
        [[ $_rice_prompt_subst_original == on ]] && setopt promptsubst
    fi
}
add-zsh-hook precmd _rice_prompt_refresh
# rice-settings:prompt-loader-end
'''
def install(data):
    for path,value in data.items():
        path=Path(path)
        if value is None:
            if path.exists():path.unlink()
        else:waybar.atomic(path,value)
def main(action):
    if action=='read':return dict(settings=read(),fields=FIELDS,presets=PRESETS,canRestore=any(STATE.glob('*.json')))
    before={str(p):p.read_text() if p.exists() else None for p in (FILE,SOURCE)}
    if action=='apply':
        data=validate(json.load(sys.stdin));changes={str(FILE):json.dumps(data,ensure_ascii=False)+'\n',str(SOURCE):render(data)}
    elif action=='restore':
        backups=sorted(STATE.glob('*.json'))
        if not backups:raise ValueError('Нет резервной копии')
        changes=json.loads(backups[-1].read_text())
        if set(changes)!=set(before):raise ValueError('Некорректная резервная копия')
    else:raise ValueError('Неизвестная команда')
    BASE.mkdir(parents=True,exist_ok=True);STATE.mkdir(parents=True,exist_ok=True)
    snapshot=STATE/(datetime.now().strftime('%Y%m%d-%H%M%S-%f')+'.json');snapshot.write_text(json.dumps(before))
    zsh=ZSHRC.read_text()
    try:
        install(changes)
        if '# rice-settings:prompt-loader' not in zsh:
            (STATE/'zshrc-before-loader.zsh').write_text(zsh)
            waybar.atomic(ZSHRC,zsh.rstrip()+'\n'+LOADER)
    except Exception:
        install(before);waybar.atomic(ZSHRC,zsh);raise
    return dict(settings=read(),canRestore=True,message='Приглашение сохранено. В уже открытом zsh один раз выполни: source ~/.zshrc. Последующие изменения появятся перед следующей командой.')
if __name__=='__main__':
    try:print(json.dumps(main(sys.argv[1]),ensure_ascii=False))
    except Exception as e:print(json.dumps(dict(error=str(e)),ensure_ascii=False));sys.exit(1)
